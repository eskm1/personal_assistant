// Writes config.js (window.STUDIO_CONFIG) from the environment. Netlify runs this
// as the build command; locally: SUPABASE_URL=… SUPABASE_ANON_KEY=… node build-config.mjs
//
//   SUPABASE_URL       https://<project>.supabase.co
//   SUPABASE_ANON_KEY  the public key: a legacy anon key (eyJ…) or a publishable key (sb_publishable_…)
//   STUDIO_URL         optional: the Studio laptop's dashboard (its Tailscale address), for
//                      "Open the draft on the laptop" links
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const env = (name) => (process.env[name] || "").trim();
const httpUrl = (name, value) => {
  if (!value) return "";
  let url;
  try { url = new URL(value); } catch { throw new Error(`${name} isn't a URL: ${value}`); }
  if (!/^https?:$/.test(url.protocol)) throw new Error(`${name} must be an http(s) URL`);
  return url.origin + url.pathname.replace(/\/+$/, "");
};

const config = {
  supabaseUrl: httpUrl("SUPABASE_URL", env("SUPABASE_URL")),
  supabaseAnonKey: env("SUPABASE_ANON_KEY"),
  studioUrl: httpUrl("STUDIO_URL", env("STUDIO_URL")),
};
if (!config.supabaseUrl || !config.supabaseAnonKey) {
  console.error("Set SUPABASE_URL and SUPABASE_ANON_KEY (Netlify: Site settings > Environment variables).");
  process.exit(1);
}
if (/^sb_secret_/.test(config.supabaseAnonKey) || /service_role/.test(Buffer.from(config.supabaseAnonKey.split(".")[1] || "", "base64").toString())) {
  console.error("SUPABASE_ANON_KEY is a secret (service role) key. Use the anon or publishable key.");
  process.exit(1);
}
if (!/\.supabase\.co$/.test(new URL(config.supabaseUrl).hostname)) {
  console.warn(`Note: ${config.supabaseUrl} isn't on supabase.co; add it to the CSP in netlify.toml.`);
}

const out = join(dirname(fileURLToPath(import.meta.url)), "config.js");
writeFileSync(out, `// Generated by build-config.mjs. Do not edit or commit.\nwindow.STUDIO_CONFIG = ${JSON.stringify(config, null, 2)};\n`);
console.log(`Wrote ${out}`);
